// Native OpenClaw owns the roster transaction, bootstrap files and identity store.
import { execFile } from 'node:child_process';
import { lstat } from 'node:fs/promises';
import { findPackageJSON } from 'node:module';
import { dirname, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { promisify } from 'node:util';

const exec = promisify(execFile);
const reserved = new Set(['main', 'openclaw', 'crestodian', 'constructor', 'prototype']);

export function creationPlan(stateDir, args) {
  const id = args?.agentId;
  if (args?.action !== 'create_agent' || Object.keys(args).some(key => !['action', 'agentId'].includes(key)) ||
      typeof id !== 'string' || !/^[a-z0-9][a-z0-9_-]{0,63}$/.test(id) || reserved.has(id))
    throw Error('agent_creation_invalid_id_or_arguments');
  return { id, workspace: join(stateDir, 'workspace-' + id), agentDir: join(stateDir, 'agents', id, 'agent') };
}

export function creationOwner(config, live, turn, ctx) {
  const channel = config.agentCreationChannelId, source = turn?.source;
  if (!channel || turn?.kind !== 'interactive' || source.channel !== 'slack' ||
      source.chatId !== channel || source.accountId !== config.channel.accountId ||
      source.agentId !== config.channel.agentId || source.sessionKey !== ctx.sessionKey) return false;
  const base = 'agent:' + source.agentId + ':slack:channel:' + channel.toLowerCase();
  if (ctx.sessionKey !== base && !(ctx.sessionKey.startsWith(base + ':thread:') &&
      /^\d+\.\d+$/.test(ctx.sessionKey.slice(base.length + 8)))) return false;
  const entry = live?.plugins?.entries?.['rein-acp'];
  return entry?.enabled !== false && entry?.config?.enabled === true && entry.config.taskLoop === true &&
    entry.config.agentCreationChannelId === channel && entry.config.additionalChannelIds?.includes(channel) &&
    entry.config.channel?.accountId === source.accountId && entry.config.channel?.agentId === source.agentId &&
    entry.config.channel?.workspaceId === config.channel.workspaceId &&
    live.commands?.ownerAllowFrom?.includes('slack:' + source.senderId) === true;
}

async function existingEntry(path) {
  try { return await lstat(path); }
  catch (error) { if (error.code === 'ENOENT') return; throw Error('agent_creation_directory_unavailable'); }
}

export function nativeAgentCreation({ stateDir, runtimeSource, env = process.env }) {
  async function cli(args, signal) {
    const manifest = findPackageJSON('openclaw', pathToFileURL(runtimeSource));
    if (!manifest) throw Error('agent_creation_cli_unavailable');
    const { stdout } = await exec(process.execPath, [join(dirname(manifest), 'openclaw.mjs'), 'agents', ...args, '--json'],
      { env: { ...env, OPENCLAW_STATE_DIR: stateDir }, signal, timeout: 60_000, maxBuffer: 4 * 1024 * 1024 });
    return JSON.parse(stdout);
  }
  return {
    plan: args => creationPlan(stateDir, args),
    async create(plan, authorize, signal) {
      const { id, workspace, agentDir } = plan;
      const list = async () => {
        try { return await cli(['list'], signal); } catch { throw Error('agent_creation_roster_unavailable'); }
      };
      const roster = await list();
      if (roster.some(agent => agent.id === id)) return { status: 'already_exists', agentId: id };
      const agentsRoot = await existingEntry(join(stateDir, 'agents'));
      if (roster.some(agent => agent.workspace === workspace || agent.agentDir === agentDir) ||
          (agentsRoot && !agentsRoot.isDirectory()) || await existingEntry(workspace) || await existingEntry(dirname(agentDir)))
        throw Error('agent_creation_directory_conflict');
      await authorize();
      // Use a fixed argv. All paths are generated by the gateway; no shell, bindings or auth-copy options.
      let acknowledged = false;
      try {
        const receipt = await cli(['add', id, '--non-interactive', '--workspace', workspace, '--agent-dir', agentDir], signal);
        acknowledged = receipt.agentId === id && receipt.workspace === workspace && receipt.agentDir === agentDir;
      } catch { /* A lost response can follow a committed write. Reconcile through the native inventory. */ }
      const verified = (await list()).find(agent => agent.id === id);
      if (!verified || verified.workspace !== workspace || verified.agentDir !== agentDir)
        throw Error('agent_creation_unverified_check_roster_before_retry');
      return { status: acknowledged ? 'created' : 'present_after_request', agentId: id, workspace, agentDir };
    },
  };
}
